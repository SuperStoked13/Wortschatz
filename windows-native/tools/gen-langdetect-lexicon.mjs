// Writes src/Wortschatz.Core/LangDetectLexicon.cs from the data of Website/src/core/langdetect.js
// (the JS reference; the Mac port has the same data in LangDetectLexicon.swift).
// Run after the lexicon changed:  node windows-native/tools/gen-langdetect-lexicon.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const src = fs.readFileSync(path.join(root, 'Website/src/core/langdetect.js'), 'utf8');
// Evaluate the module's data section without its import (the data needs no other module).
const body = src.replace(/^import .*$/m, '') +
  '\nexport { FUNCTION_WORDS, VOCAB_WORDS, LEXICON_ONLY, LEADING, DE_DETERMINERS, CHAR_WEIGHTS, SUFFIXES, CONSONANT_END, NGRAMS };';
const mod = await import('data:text/javascript;base64,' + Buffer.from(body.replace(/normalizeBasic/g, 'String')).toString('base64'));

const cs = (s) => JSON.stringify(s);
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const weights = (o) => `[${Object.entries(o).map(([l, w]) => `(${cs(l)}, ${num(w)})`).join(', ')}]`;
const words = (o) => Object.entries(o).map(([l, s]) => `        [${cs(l)}] = ${cs(s.split(/\s+/).filter(Boolean).join(' '))},`).join('\n');

const out = `// <auto-generated> by windows-native/tools/gen-langdetect-lexicon.mjs from Website/src/core/langdetect.js.
// Do not edit by hand: change the JS (and LangDetectLexicon.swift on the Mac), then run the generator.
namespace Wortschatz.Core;

/// <summary>The data of the language detector (port of LangDetectLexicon.swift).</summary>
internal static class LangDetectLexicon
{
    /// <summary>Space-separated words per language (lower case; ß written as ss).</summary>
    public static readonly Dictionary<string, string> FUNCTION_WORDS = new()
    {
${words(mod.FUNCTION_WORDS)}
    };

    public static readonly Dictionary<string, string> VOCAB_WORDS = new()
    {
${words(mod.VOCAB_WORDS)}
    };

    public static readonly Dictionary<string, string> LEXICON_ONLY = new()
    {
${words(mod.LEXICON_ONLY)}
    };

    /// <summary>Article / pronoun at the start of a line or segment → (lang, weight) in JS order.</summary>
    public static readonly Dictionary<string, (string Lang, double W)[]> LEADING = new(StringComparer.Ordinal)
    {
${Object.entries(mod.LEADING).map(([k, v]) => `        [${cs(k)}] = ${weights(v)},`).join('\n')}
    };

    public static readonly HashSet<string> DE_DETERMINERS = new(StringComparer.Ordinal)
    {
        ${[...mod.DE_DETERMINERS].filter(Boolean).map(cs).join(', ')},
    };

    public static readonly Dictionary<char, (string Lang, double W)[]> CHAR_WEIGHTS = new()
    {
${Object.entries(mod.CHAR_WEIGHTS).map(([k, v]) => `        ['${k}'] = ${weights(v)},`).join('\n')}
    };

    public static readonly Dictionary<string, (string Suffix, double W)[]> SUFFIXES = new()
    {
${Object.entries(mod.SUFFIXES).map(([l, list]) => `        [${cs(l)}] = [${list.map(([s, w]) => `(${cs(s)}, ${num(w)})`).join(', ')}],`).join('\n')}
    };

    public static readonly (string Lang, double W)[] CONSONANT_END = ${weights(mod.CONSONANT_END)};

    public static readonly (string Gram, (string Lang, double W)[] Weights)[] NGRAMS =
    [
${mod.NGRAMS.map(([g, w]) => `        (${cs(g)}, ${weights(w)}),`).join('\n')}
    ];
}
`;
fs.writeFileSync(path.join(root, 'windows-native/src/Wortschatz.Core/LangDetectLexicon.cs'), out);
console.log('wrote LangDetectLexicon.cs');
